function touchRoom(room) {
  room.lastActivityAt = Date.now();
}

function makeCode() {
  const chars = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789";
  let code;
  do {
    code = Array.from({ length: 4 }, () => chars[Math.floor(Math.random() * chars.length)]).join("");
  } while (rooms.has(code));
  return code;
}

function shuffledQuestion(room) {
  const used = new Set(room.usedQuestions);
  let candidates = QUESTION_BANK.filter((_, i) => !used.has(i));
  if (!candidates.length) {
    room.usedQuestions = [];
    candidates = QUESTION_BANK.slice();
  }
  const index = Math.floor(Math.random() * candidates.length);
  const q = candidates[index];
  const originalIndex = QUESTION_BANK.indexOf(q);
  room.usedQuestions.push(originalIndex);
  return {
    id: crypto.randomUUID(),
    text: q.text,
    options: q.options
  };
}

function safeRoom(room) {
  return {
    code: room.code,
    players: room.players.map(p => ({ id: p.id, name: p.name, connected: !!p.ws && p.ws.readyState === WebSocket.OPEN })),
    phase: room.phase,
    round: room.round,
    totalRounds: room.totalRounds,
    question: room.question,
    answers: room.answers,
    scores: room.scores,
    winner: room.winner || null
  };
}

function send(ws, type, data = {}) {
  if (ws && ws.readyState === WebSocket.OPEN) {
    ws.send(JSON.stringify({ type, ...data }));
  }
}

function broadcast(room, type, data = {}) {
  touchRoom(room);
  room.players.forEach(p => send(p.ws, type, data));
}

function resetRoom(room) {
  room.phase = "waiting";
  room.round = 0;
  room.question = null;
  room.answers = {};
  room.scores = {};
  room.usedQuestions = [];
  room.winner = null;
  room.players.forEach(p => room.scores[p.id] = 0);
}

function startGame(room) {
  if (room.players.length !== 2) return;
  room.phase = "answering";
  room.round = 1;
  room.question = shuffledQuestion(room);
  room.answers = {};
  room.scores = {};
  room.players.forEach(p => room.scores[p.id] = 0);
  broadcast(room, "game_started", {
    room: safeRoom(room),
    message: "เกมเริ่มแล้ว!"
  });
  broadcast(room, "round_started", {
    round: room.round,
    totalRounds: room.totalRounds,
    question: room.question
  });
}

function finishRound(room) {
  const ids = room.players.map(p => p.id);
  const a = room.answers[ids[0]];
  const b = room.answers[ids[1]];

  let same = false;
  if (a && b) {
    same = a.choice === b.choice;
    if (same) {
      room.scores[ids[0]] += 100;
      room.scores[ids[1]] += 100;
    } else {
      room.scores[ids[0]] += 10;
      room.scores[ids[1]] += 10;
    }
  }

  room.phase = "round_result";
  broadcast(room, "round_result", {
    round: room.round,
    question: room.question,
    answers: room.answers,
    same,
    scores: room.scores,
    bonus: same ? 100 : 10
  });

  setTimeout(() => {
    if (!rooms.has(room.code)) return;
    if (room.round >= room.totalRounds) {
      finishGame(room);
      return;
    }
    room.round += 1;
    room.phase = "answering";
    room.question = shuffledQuestion(room);
    room.answers = {};
    broadcast(room, "round_started", {
      round: room.round,
      totalRounds: room.totalRounds,
      question: room.question
    });
  }, 2800);
}

function finishGame(room) {
  room.phase = "finished";
  const ids = room.players.map(p => p.id);
  const s0 = room.scores[ids[0]] || 0;
  const s1 = room.scores[ids[1]] || 0;
  let winner = "draw";
  if (s0 > s1) winner = ids[0];
  if (s1 > s0) winner = ids[1];
  room.winner = winner;

  broadcast(room, "game_finished", {
    scores: room.scores,
    winner,
    players: room.players.map(p => ({ id: p.id, name: p.name }))
  });
}

function removePlayer(room, playerId) {
  const idx = room.players.findIndex(p => p.id === playerId);
  if (idx >= 0) room.players.splice(idx, 1);
  if (room.players.length === 0) {
    rooms.delete(room.code);
    return;
  }
  room.phase = "waiting";
  room.question = null;
  room.answers = {};
  room.winner = null;
  room.players.forEach(p => room.scores[p.id] = 0);
  broadcast(room, "opponent_left", { message: "เพื่อนออกจากห้องแล้ว" });
}

