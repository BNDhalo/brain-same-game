// Keep public WebSocket sessions healthy and help free hosts detect stale clients.
const heartbeatTimer = setInterval(() => {
  for (const [code, room] of rooms) {
    if (Date.now() - room.lastActivityAt > ROOM_TTL_MS && room.phase === "waiting") {
      room.players.forEach(p => {
        try { p.ws.close(1000, "room expired"); } catch {}
      });
      rooms.delete(code);
      continue;
    }
    room.players.forEach(p => {
      if (p.ws && p.ws.readyState === WebSocket.OPEN) {
        try { p.ws.ping(); } catch {}
      }
    });
  }
}, HEARTBEAT_MS);
heartbeatTimer.unref?.();

wss.on("connection", ws => {
  ws.id = crypto.randomUUID();
  ws.roomCode = null;

  ws.on("message", raw => {
    let msg;
    try { msg = JSON.parse(raw.toString()); } catch { return send(ws, "error", { message: "ข้อมูลไม่ถูกต้อง" }); }

    if (msg.type === "ping") {
      const currentRoom = ws.roomCode ? rooms.get(ws.roomCode) : null;
      if (currentRoom) touchRoom(currentRoom);
      return;
    }

    if (msg.type === "create_room") {
      if (ws.roomCode) return send(ws, "error", { message: "คุณอยู่ในห้องแล้ว" });
      const code = makeCode();
      const player = { id: ws.id, name: String(msg.name || "ผู้เล่น 1").slice(0, 18), ws };
      const room = {
        code,
        players: [player],
        phase: "waiting",
        round: 0,
        totalRounds: 15,
        question: null,
        answers: {},
        scores: { [player.id]: 0 },
        usedQuestions: [],
        winner: null,
        lastActivityAt: Date.now()
      };
      rooms.set(code, room);
      ws.roomCode = code;
      send(ws, "room_created", { code, playerId: ws.id, room: safeRoom(room) });
      return;
    }

    if (msg.type === "join_room") {
      if (ws.roomCode) return send(ws, "error", { message: "คุณอยู่ในห้องแล้ว" });
      const code = String(msg.code || "").trim().toUpperCase();
      const room = rooms.get(code);
      if (!room) return send(ws, "error", { message: "ไม่พบห้องนี้" });
      touchRoom(room);
      if (room.players.length >= 2) return send(ws, "error", { message: "ห้องเต็มแล้ว" });
      if (room.phase !== "waiting") return send(ws, "error", { message: "เกมห้องนี้เริ่มไปแล้ว" });

      const player = { id: ws.id, name: String(msg.name || "ผู้เล่น 2").slice(0, 18), ws };
      room.players.push(player);
      room.scores[player.id] = 0;
      ws.roomCode = code;

      room.players.forEach(p => send(p.ws, "room_joined", {
        code,
        playerId: p.id,
        room: safeRoom(room)
      }));
      return;
    }

    const room = ws.roomCode ? rooms.get(ws.roomCode) : null;
    if (room) touchRoom(room);
    if (!room) return send(ws, "error", { message: "กรุณาสร้างหรือเข้าห้องก่อน" });

    if (msg.type === "start_game") {
      if (room.players.length !== 2) return send(ws, "error", { message: "ต้องมีผู้เล่นครบ 2 คนก่อน" });
      if (room.phase !== "waiting") return send(ws, "error", { message: "เกมกำลังเล่นอยู่" });
      startGame(room);
      return;
    }

    if (msg.type === "answer") {
      if (room.phase !== "answering") return;
      if (!room.players.some(p => p.id === ws.id)) return;
      if (room.answers[ws.id]) return send(ws, "error", { message: "ตอบไปแล้ว" });
      const choice = Number(msg.choice);
      if (!Number.isInteger(choice) || choice < 0 || choice > 3) return send(ws, "error", { message: "คำตอบไม่ถูกต้อง" });

      room.answers[ws.id] = { choice, at: Date.now() };
      send(ws, "answer_locked", { choice });

      const other = room.players.find(p => p.id !== ws.id);
      if (other) send(other.ws, "opponent_answered", { message: "เพื่อนตอบแล้ว! 👀" });

      if (Object.keys(room.answers).length === 2) finishRound(room);
      return;
    }

    if (msg.type === "play_again") {
      if (room.phase !== "finished") return;
      resetRoom(room);
      broadcast(room, "back_to_lobby", { room: safeRoom(room) });
      return;
    }
  });

  ws.on("close", () => {
    const code = ws.roomCode;
    if (!code) return;
    const room = rooms.get(code);
    if (!room) return;
    removePlayer(room, ws.id);
  });
});

server.listen(PORT, HOST, () => {
  console.log(`Brain Same Game running on port ${PORT}`);
});
